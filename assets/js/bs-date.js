  const DIGITS_NE = "०१२३४५६७८९";

  function monthLength(y, m) { const r = MONTH_DAYS[y - START_YEAR]; return r ? r[m - 1] : null; }
  function adDayNum(y, m, d) { return Date.UTC(y, m - 1, d) / DAY_MS; }
  function fromDayNum(n) { const t = new Date(n * DAY_MS); return { y: t.getUTCFullYear(), m: t.getUTCMonth() + 1, d: t.getUTCDate(), dow: t.getUTCDay() }; }

  /* BS → AD. Returns {error} or {y, m, d, dow, dayNum} */
  function bsToAd(y, m, d) {
    if (!Number.isInteger(y) || y < START_YEAR || y > END_YEAR) return { error: "Supported years: " + START_YEAR + "–" + END_YEAR + " BS" };
    if (!Number.isInteger(m) || m < 1 || m > 12) return { error: "Choose a month" };
    const len = monthLength(y, m);
    if (!Number.isInteger(d) || d < 1 || d > len) return { error: MONTHS_EN[m - 1] + " " + y + " has " + len + " days" };
    let days = 0;
    for (let i = 0; i < y - START_YEAR; i++) days += YEAR_TOTALS[i];
    const row = MONTH_DAYS[y - START_YEAR];
    for (let i = 0; i < m - 1; i++) days += row[i];
    const dayNum = EPOCH_DAY + days + d - 1;
    return Object.assign(fromDayNum(dayNum), { dayNum });
  }

  /* AD → BS. Returns {y, m, d, dow} or null when out of range */
  function adToBs(ay, am, ad) {
    const dn = adDayNum(ay, am, ad);
    let rem = dn - EPOCH_DAY;
    if (rem < 0) return null;
    for (let i = 0; i < MONTH_DAYS.length; i++) {
      if (rem < YEAR_TOTALS[i]) {
        const row = MONTH_DAYS[i];
        for (let m = 0; m < 12; m++) {
          if (rem < row[m]) return { y: START_YEAR + i, m: m + 1, d: rem + 1, dow: fromDayNum(dn).dow };
          rem -= row[m];
        }
      }
      rem -= YEAR_TOTALS[i];
    }
    return null;
  }

  /* Today's date on the visitor's own device */
  function todayAd() { const t = new Date(); return { y: t.getFullYear(), m: t.getMonth() + 1, d: t.getDate(), dow: t.getDay() }; }
  function todayBs() { const t = todayAd(); return adToBs(t.y, t.m, t.d); }
  function toNepaliDigits(v) { return String(v).replace(/[0-9]/g, c => DIGITS_NE[+c]); }

